#!/usr/bin/env bash
#
# Run GPUI's OWN Rust examples, straight from the crate.
#
#   ./tools/upstream-examples.sh list
#   ./tools/upstream-examples.sh run hello_world
#   ./tools/upstream-examples.sh build uniform_list
#
# The point is triage: these are the same widgets, driven by GPUI's own code,
# with no binding and no Gossamer in the picture. When something misbehaves in
# examples/, running the upstream example for it separates three cases:
#
#   * it works upstream and not here  -> the binding, or the Gosammer toolchain
#   * it misbehaves in both           -> gpui itself
#   * it works here and not upstream  -> unlikely; check your own changes
#
# `tools/upstream/` is generated and gitignored. It pins the SAME gpui version
# the binding pins, read out of gpui-binding/Cargo.toml.

set -euo pipefail

cd "$(dirname "$0")/.."

UPSTREAM="tools/upstream"
MANIFEST="gpui-binding/Cargo.toml"

version=$(sed -n 's/^gpui = { version = "\([^"]*\)".*/\1/p' "$MANIFEST" | head -1)
if [ -z "$version" ]; then
  echo "upstream-examples: could not read the gpui version from $MANIFEST" >&2
  exit 1
fi

# gpui's examples that need a crate the zed workspace does not publish.
skip="image_gallery"

sync() {
  local gpui_line src crate file ex_name dir
  mkdir -p "$UPSTREAM"

  if [ "$(uname -s)" = "Darwin" ]; then
    gpui_line="gpui = { version = \"$version\", features = [\"runtime_shaders\"] }"
  else
    gpui_line="gpui = { version = \"$version\", default-features = false, features = [\"x11\"] }"
  fi

  cat > "$UPSTREAM/Cargo.toml" <<EOF
# generated by tools/upstream-examples.sh -- do not edit
[package]
name = "gpui-upstream-examples"
version = "0.0.0"
edition = "2024"
publish = false

[workspace]

# gpui's own workspace supplies these to its examples as dev-dependencies,
# which cargo does not publish. Versions are the ones its Cargo.toml names.
[dependencies]
$gpui_line
anyhow = "1"
env_logger = "0.11"
log = "0.4"
lyon = { version = "1", features = ["extra"] }
rand = "0.9"
unicode-segmentation = "1"
EOF

  # Find the extracted crate, or extract it from the registry cache. `cargo
  # fetch` first, so a cold machine has the .crate to work from.
  src=$(ls -d ~/.cargo/registry/src/*/gpui-"$version" 2>/dev/null | head -1 || true)
  if [ -z "$src" ]; then
    ( cd "$UPSTREAM" && printf 'fn main() {}\n' > placeholder.rs && cargo fetch >/dev/null 2>&1 || true )
    src=$(ls -d ~/.cargo/registry/src/*/gpui-"$version" 2>/dev/null | head -1 || true)
  fi
  if [ -z "$src" ]; then
    src=$(mktemp -d)
    crate=$(ls ~/.cargo/registry/cache/*/gpui-"$version".crate 2>/dev/null | head -1 || true)
    if [ -z "$crate" ]; then
      echo "upstream-examples: gpui $version is not in the cargo cache." >&2
      echo "  Run 'cargo fetch' in $UPSTREAM once, then retry." >&2
      exit 1
    fi
    tar xzf "$crate" -C "$src" --strip-components=1 "gpui-$version/examples"
  fi

  rm -rf "$UPSTREAM/examples"
  mkdir -p "$UPSTREAM/examples"
  for file in "$src"/examples/*.rs; do
    ex_name=$(basename "$file" .rs)
    case " $skip " in *" $ex_name "*) continue ;; esac
    cp "$file" "$UPSTREAM/examples/"
  done
  # Some examples load images or SVGs from beside themselves.
  for dir in image svg; do
    [ -d "$src/examples/$dir" ] && cp -R "$src/examples/$dir" "$UPSTREAM/examples/"
  done
  rm -f "$UPSTREAM/placeholder.rs"
}

case "${1:-}" in
list)
  sync
  echo "gpui $version examples (upstream, unmodified):"
  for file in "$UPSTREAM"/examples/*.rs; do
    printf '  %s\n' "$(basename "$file" .rs)"
  done
  echo
  echo "usage: ./tools/upstream-examples.sh run <name>"
  ;;
run | build)
  action="$1"; shift
  [ $# -gt 0 ] || { echo "upstream-examples: which example?" >&2; exit 1; }
  name="${1#examples/}"; name="${name%.rs}"; shift
  sync
  if [ ! -f "$UPSTREAM/examples/$name.rs" ]; then
    echo "upstream-examples: no example named '$name' (try: list)" >&2
    exit 1
  fi
  if [ "$action" = build ]; then
    exec cargo build --manifest-path "$UPSTREAM/Cargo.toml" --example "$name" "$@"
  fi
  exec cargo run --manifest-path "$UPSTREAM/Cargo.toml" --example "$name" "$@"
  ;;
*)
  echo "usage: ./tools/upstream-examples.sh list | run <name> | build <name>" >&2
  exit 1
  ;;
esac
